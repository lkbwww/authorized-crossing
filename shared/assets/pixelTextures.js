/**
 * Runtime-generated pixel textures.
 * This keeps the project static-host friendly without external art files.
 */
function generate(scene, key, data, palette) {
  if (scene.textures.exists(key)) {
    return;
  }
  scene.textures.generate(key, {
    data,
    pixelWidth: 1,
    palette,
  });
}


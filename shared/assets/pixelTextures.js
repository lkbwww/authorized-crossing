export function getSeasonTreeTexture(seasonKey) {
  if (seasonKey === "SPRING") {
    return "tree-spring";
  }
  if (seasonKey === "SUMMER") {
    return "tree-summer";
  }
  if (seasonKey === "AUTUMN") {
    return "tree-autumn";
  }
  return "tree-winter";
}
